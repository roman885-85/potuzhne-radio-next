/*  ---------------------------------------------------------------------------
 *  Bluetooth-колонка окремим режимом.
 *
 *  Рішення власника: не «ще одне джерело поряд із радіо», а окремий режим із
 *  перезавантаженням. Причина — пам'ять: класичний Bluetooth забирає десятки
 *  кілобайтів, і тримати його разом із Wi-Fi, потоком і карткою на ESP32 з
 *  4 МБ без PSRAM означає працювати на межі. Тому: прапорець у NVS →
 *  перезавантаження → на старті піднімається або радіо, або колонка.
 *
 *  Звук іде повз декодер: A2DP віддає готові відліки, ми шлемо їх у VS1053
 *  як WAV (Audio::pcmBegin/pcmFeed). Wi-Fi у цьому режимі не піднімаємо.
 *  ------------------------------------------------------------------------- */
#ifndef yoBt_h
#define yoBt_h

#include <Arduino.h>

namespace yobt {

bool        wanted();                 /* прапорець у NVS: наступний старт — колонкою */
void        setWanted(bool on);       /* записати прапорець і перезавантажитись */
bool        active();                 /* цей старт — колонка */
void        begin();                  /* підняти A2DP (звати замість мережі радіо) */
const char* peer();                   /* ім'я під'єднаного пристрою або "" */
bool        playing();

}  // namespace yobt
#endif
